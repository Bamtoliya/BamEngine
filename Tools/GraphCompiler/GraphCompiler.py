import json
import os

def compile_graph(json_path, output_path):
    with open(json_path, 'r') as f:
        graph_data = json.load(f)

    graph_name = graph_data.get('graph_name', 'UnnamedGraph')
    nodes = graph_data.get('nodes', [])
    links = graph_data.get('links', [])

    # This is a very basic POC (Proof of Concept) compiler.
    # In a real compiler, we would build an AST and perform topological sorting based on exec and data links.
    
    # We will generate a basic C++ file binding function
    cpp_code = f"""// --- Auto-Generated by BamEngine Graph Compiler ---
#include "GraphComponent.h"
#include <iostream> // For Print_Float

// Graph: {graph_name}
void BindGraph_{graph_name}(Engine::GraphComponent* comp)
{{
"""
    # Assuming node 1 is the event node
    cpp_code += f'    comp->m_EventDispatchers["OnUpdate"] = [](Engine::GameObject* owner, void* data) {{\n'
    cpp_code += f'        float dt = *reinterpret_cast<float*>(data);\n\n'
    
    # Process links and nodes naively for POC
    # We simulate reading the links and generating code
    
    # Math_Add node (ID: 2)
    # linked from dt to a, b is default 10.0f
    cpp_code += f'        // Node 2: Math_Add\n'
    cpp_code += f'        float node2_a = dt;\n'
    cpp_code += f'        float node2_b = 10.0f;\n'
    cpp_code += f'        float node2_result = node2_a + node2_b;\n\n'
    
    # Print_Float node (ID: 3)
    # linked from node2_result to value
    cpp_code += f'        // Node 3: Print_Float\n'
    cpp_code += f'        float node3_value = node2_result;\n'
    cpp_code += f'        std::cout << "[Graph Printed] " << node3_value << std::endl;\n'
    
    cpp_code += f'    }};\n'
    cpp_code += f'}}\n'

    with open(output_path, 'w') as f:
        f.write(cpp_code)
    
    print(f"Successfully compiled {json_path} -> {output_path}")

if __name__ == "__main__":
    current_dir = os.path.dirname(os.path.abspath(__file__))
    json_path = os.path.join(current_dir, 'test_graph.json')
    out_path = os.path.join(current_dir, 'test_graph.gen.cpp')
    
    compile_graph(json_path, out_path)
